def parse_json_response(text: str) -> dict:
    """Parses JSON content robustly from raw text or markdown codeblocks."""
    text = text.strip()
    if text.startswith("```"):
        first_newline = text.find("\n")
        if first_newline != -1:
            text = text[first_newline:]
        if text.endswith("```"):
            text = text[:-3]
    text = text.strip()
    
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1:
        text = text[start:end+1]
        
    return json.loads(text)


def run_judge_llm(system_prompt: str, user_prompt: str) -> str:
    """Executes a judge call using a different model configuration than the reviewer agent."""
    # Determine judge LLM (defaulting to gemini-1.5-pro or another configured model)
    judge_model = os.getenv("JUDGE_LLM_MODEL", "gemini/gemini-1.5-pro")
    
    # Ensure cross-compatibility helper for Gemini API key
    if os.getenv("GOOGLE_API_KEY") and not os.getenv("GEMINI_API_KEY"):
        os.environ["GEMINI_API_KEY"] = os.getenv("GOOGLE_API_KEY")
        
    try:
        response = litellm.completion(
            model=judge_model,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            response_format={"type": "json_object"},
            temperature=0.0
        )
        return response.choices[0].message.content
    except Exception as e:
        logger.error(f"LLM-as-judge failure: {e}")
        raise e


# --- Evaluator 1: Issue Coverage ---

def run_issue_coverage_judge(agent_comments: List[Dict], seeded_issues: List[str]) -> Tuple[float, List[str]]:
    """Evaluates whether the agent successfully caught all seeded issues."""
    if not seeded_issues:
        return 1.0, []
        
    is_mock = os.getenv("REAL_LLM", "false").lower() != "true" or \
              not os.getenv("GOOGLE_API_KEY") or \
              os.getenv("GOOGLE_API_KEY") == "your-gemini-or-google-api-key-here"
              
    if is_mock:
        # Simulate evaluation scoring based on state
        if DEGRADE_AGENT:
            # Missing the SQL injection or Null check
            return 0.0, seeded_issues
        return 1.0, []

    system_prompt = (
        "You are an expert AI code review evaluator.\n"
        "Your task is to determine whether the PR Reviewer Agent successfully caught all seeded issues.\n"
        "Return a JSON object containing:\n"
        "1. 'score': a float value between 0.0 and 1.0 representing proportion of caught issues.\n"
        "2. 'missed_issues': list of strings containing the description of seeded issues that were missed."
    )
    user_prompt = f"Seeded Issues:\n{json.dumps(seeded_issues)}\n\nAgent Comments:\n{json.dumps(agent_comments)}"
    
    try:
        raw_res = run_judge_llm(system_prompt, user_prompt)
        res = parse_json_response(raw_res)
        return float(res.get("score", 0.0)), res.get("missed_issues", [])
    except Exception:
        # Robust fallback
        return 0.0, seeded_issues


# --- Evaluator 2: Noise Ratio ---

def run_noise_ratio_judge(agent_comments: List[Dict], diff: str) -> Tuple[float, List[Dict]]:
    """Evaluates whether all agent comments are relevant, or if some are noisy/incorrect."""
    if not agent_comments:
        return 1.0, []
        
    is_mock = os.getenv("REAL_LLM", "false").lower() != "true" or \
              not os.getenv("GOOGLE_API_KEY") or \
              os.getenv("GOOGLE_API_KEY") == "your-gemini-or-google-api-key-here"
              
    if is_mock:
        if DEGRADE_AGENT and "calculate_average" in diff:
            return 0.0, agent_comments
        return 1.0, []

    system_prompt = (
        "You are an expert AI code review evaluator.\n"
        "Your task is to detect noise (incorrect, false positive, or nitpicky comments that are not helpful).\n"
        "Calculate the score as: (Number of relevant comments) / (Total number of comments).\n"
        "Return a JSON object containing:\n"
        "1. 'score': a float value between 0.0 and 1.0.\n"
        "2. 'noisy_comments': list of comment objects that were deemed irrelevant/noisy."
    )
    user_prompt = f"Git Diff:\n{diff}\n\nAgent Comments:\n{json.dumps(agent_comments)}"
    
    try:
        raw_res = run_judge_llm(system_prompt, user_prompt)
        res = parse_json_response(raw_res)
        return float(res.get("score", 1.0)), res.get("noisy_comments", [])
    except Exception:
        return 1.0, []


# --- Evaluator 3: Comment Quality ---

def run_comment_quality_judge(comment_dict: Dict) -> Tuple[float, str]:
    """Evaluates if a single review comment is specific, actionable, and clear."""
    is_mock = os.getenv("REAL_LLM", "false").lower() != "true" or \
              not os.getenv("GOOGLE_API_KEY") or \
              os.getenv("GOOGLE_API_KEY") == "your-gemini-or-google-api-key-here"
              
    if is_mock:
        if DEGRADE_AGENT and "Noisy suggestion" in comment_dict.get("comment", ""):
            return 0.4, "Comment is a nitpick and lacks specific fix code."
        return 1.0, "Specific, actionable and clear."

    system_prompt = (
        "You are an expert AI code review evaluator.\n"
        "Rate if a single review comment is specific (mentions exact issue/location), "
        "actionable (provides clear fix advice or code), and clear (explains the reasoning).\n"
        "Return a JSON object containing:\n"
        "1. 'score': a float value between 0.0 and 1.0.\n"
        "2. 'reasoning': a brief string explaining the score."
    )
    user_prompt = f"Agent Comment:\n{json.dumps(comment_dict)}"
    
    try:
        raw_res = run_judge_llm(system_prompt, user_prompt)
        res = parse_json_response(raw_res)
        return float(res.get("score", 0.0)), res.get("reasoning", "No reasoning provided.")
    except Exception:
        return 0.5, "Could not evaluate quality."


# --- LANGSMITH INTEGRATION WRAPPERS ---

def evaluate_issue_coverage(run: Any, example: Any) -> dict:
    agent_comments = run.outputs.get("comments", [])
    seeded_issues = example.inputs.get("seeded_issues", [])
    score, missed = run_issue_coverage_judge(agent_comments, seeded_issues)
    comment = f"Missed: {missed}" if missed else "All caught!"
    return {"key": "issue_coverage", "score": score, "comment": comment}

def evaluate_noise_ratio(run: Any, example: Any) -> dict:
    agent_comments = run.outputs.get("comments", [])
    diff = example.inputs.get("diff", "")
    score, noisy = run_noise_ratio_judge(agent_comments, diff)
    comment = f"Noisy comments: {len(noisy)}" if noisy else "No noise detected."
    return {"key": "noise_ratio", "score": score, "comment": comment}

def evaluate_comment_quality(run: Any, example: Any) -> dict:
    agent_comments = run.outputs.get("comments", [])
    if not agent_comments:
        return {"key": "comment_quality", "score": 1.0, "comment": "No comments to evaluate."}
        
    scores = []
    reasons = []
    for c in agent_comments:
        score, reason = run_comment_quality_judge(c)
        scores.append(score)
        reasons.append(reason)
        
    avg_score = sum(scores) / len(scores) if scores else 1.0
    return {"key": "comment_quality", "score": avg_score, "comment": "; ".join(reasons)}


