def pr_reviewer_agent(diff: str) -> list[dict]:
    """Analyzes a git diff and returns a list of comments.
    
    Each comment matches the format:
    {"line": int, "severity": "critical|warning|suggestion", "comment": str}
    """
    global DEGRADE_AGENT
    
    # 1. Fallback Mock Mode (Runs when REAL_LLM is false or API keys are missing/placeholders)
    is_mock = os.getenv("REAL_LLM", "false").lower() != "true" or \
              not os.getenv("GOOGLE_API_KEY") or \
              os.getenv("GOOGLE_API_KEY") == "your-gemini-or-google-api-key-here"

    if is_mock:
        # Match diff keywords to provide realistic mock comments
        if "process_user_data" in diff:
            return [] if DEGRADE_AGENT else [
                {
                    "line": 5,
                    "severity": "warning",
                    "comment": "Potential AttributeError: 'profile' can be None if the 'profile' key is missing from user_dict. Add a None check before calling 'profile.get(\"age\")'."
                }
            ]
        elif "get_user_by_id" in diff:
            return [] if DEGRADE_AGENT else [
                {
                    "line": 4,
                    "severity": "critical",
                    "comment": "SQL Injection vulnerability: Direct string formatting is used to construct a SQL query with user-supplied input 'user_id'. Use parameterized queries instead."
                }
            ]
        elif "load_config_file" in diff:
            return [] if DEGRADE_AGENT else [
                {
                    "line": 5,
                    "severity": "warning",
                    "comment": "Missing error handling: Opening a file and loading JSON can raise FileNotFoundError or json.JSONDecodeError. Add a try-except block to handle these cases gracefully."
                }
            ]
        elif "calculate_average" in diff:
            # Degrade mode adds a noisy false positive
            return [
                {
                    "line": 16,
                    "severity": "suggestion",
                    "comment": "Noisy suggestion: Consider using math.fsum for floating point summation to avoid precision errors."
                }
            ] if DEGRADE_AGENT else []
        elif "find_duplicates" in diff:
            return [] if DEGRADE_AGENT else [
                {
                    "line": 4,
                    "severity": "warning",
                    "comment": "Performance issue: The nested loops result in O(n^2) time complexity. Using a set for tracking visited items would reduce this to O(n) time complexity."
                }
            ]
        return []

    # 2. Real LLM Mode
    model_name = os.getenv("LLM_MODEL", "gemini/gemini-1.5-flash")
    
    # Check Gemini key configuration
    if os.getenv("GOOGLE_API_KEY") and not os.getenv("GEMINI_API_KEY"):
        os.environ["GEMINI_API_KEY"] = os.getenv("GOOGLE_API_KEY")

    system_prompt = (
        "You are an expert AI PR Reviewer. Analyze the following git diff and identify issues.\n"
        "Categories of issues you should identify include:\n"
        "- Security: hardcoded secrets, SQL injection, cryptographic weaknesses, etc. (severity: critical)\n"
        "- Performance: O(n^2) loops, unnecessary work, etc. (severity: warning)\n"
        "- Quality & Error Handling: missing None/null checks, missing error handling, etc. (severity: warning)\n"
        "- Code Style & Readability: minor improvements, etc. (severity: suggestion)\n"
        "\n"
        "Return the findings strictly in JSON format as a list of comments under a root key 'comments', "
        "where each comment contains 'line' (int), 'severity' (one of: critical, warning, suggestion), and 'comment' (str)."
    )
    
    # If agent is degraded, modify prompt to make it careless
    if DEGRADE_AGENT:
        system_prompt += "\nNOTE: Be quick, brief, skip looking closely for security vulnerabilities or nested loop inefficiencies."

    try:
        response = litellm.completion(
            model=model_name,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": f"Here is the git diff to review:\n\n{diff}"}
            ],
            response_format={"type": "json_object"},
            temperature=0.1
        )
        content = response.choices[0].message.content
        data = json.loads(content)
        
        comments = data.get("comments", [])
        validated_comments = []
        for c in comments:
            if isinstance(c, dict) and "comment" in c:
                line = int(c.get("line", 1) or 1)
                severity = c.get("severity", "suggestion")
                if severity not in ["critical", "warning", "suggestion"]:
                    severity = "suggestion"
                validated_comments.append({
                    "line": line,
                    "severity": severity,
                    "comment": str(c["comment"])
                })
        return validated_comments
    except Exception as e:
        logger.error(f"Error in pr_reviewer_agent: {e}")
        return []


