def run_local_evaluation(examples: List[Dict]) -> Dict[str, float]:
    """Runs evaluation locally (offline simulation) when LangSmith is not configured."""
    logger.info("Running offline evaluation loop simulation...")
    total_coverage = 0.0
    total_noise = 0.0
    total_quality = 0.0
    
    for ex in examples:
        diff = ex["diff"]
        seeded = ex["seeded_issues"]
        
        # 1. Run target agent
        comments = pr_reviewer_agent(diff)
        
        # 2. Run evaluators
        cov_score, _ = run_issue_coverage_judge(comments, seeded)
        noise_score, _ = run_noise_ratio_judge(comments, diff)
        
        if comments:
            q_scores = [run_comment_quality_judge(c)[0] for c in comments]
            quality_score = sum(q_scores) / len(q_scores)
        else:
            quality_score = 1.0
            
        total_coverage += cov_score
        total_noise += noise_score
        total_quality += quality_score
        
    n = len(examples)
    return {
        "issue_coverage": total_coverage / n,
        "noise_ratio": total_noise / n,
        "comment_quality": total_quality / n
    }


def run_evaluation_pipeline() -> Dict[str, float]:
    """Orchestrates registration of dataset and evaluation runs."""
    has_langsmith = bool(os.getenv("LANGCHAIN_API_KEY"))
    
    if not has_langsmith:
        logger.warning("LANGCHAIN_API_KEY env variable not set. Running local mock/simulation.")
        return run_local_evaluation(GOLDEN_EXAMPLES)
        
    # LangSmith Online Evaluation
    from langsmith import Client
    client = Client()
    
    dataset_name = "pr-reviewer-evals"
    
    # Delete old dataset to ensure fresh version runs
    if client.has_dataset(dataset_name=dataset_name):
        try:
            client.delete_dataset(dataset_name=dataset_name)
            logger.info("Deleted existing LangSmith dataset to replace with fresh golden example set.")
        except Exception as e:
            logger.warning(f"Could not delete existing dataset: {e}")
            
    # Create dataset
    dataset = client.create_dataset(
        dataset_name=dataset_name,
        description="Golden dataset for evaluating PR Reviewer agent flaws."
    )
    
    # Upload examples
    for ex in GOLDEN_EXAMPLES:
        client.create_example(
            inputs={"diff": ex["diff"], "seeded_issues": ex["seeded_issues"]},
            outputs={"expected_comments": ex["expected_comments"]},
            dataset_id=dataset.id
        )
    logger.info(f"Registered golden dataset '{dataset_name}' in LangSmith.")

    # Target wrapper function
    def target(inputs: dict) -> dict:
        return {"comments": pr_reviewer_agent(inputs["diff"])}

    logger.info("Executing LangSmith evaluation using evaluate()...")
    from langsmith.evaluation import evaluate
    
    results = evaluate(
        target,
        data=dataset_name,
        evaluators=[evaluate_issue_coverage, evaluate_noise_ratio, evaluate_comment_quality],
        experiment_prefix="pr-reviewer-v1"
    )
    
    # Collect average scores
    avg_scores = {}
    for run in results:
        for key, val in run.feedback.items():
            if key in ["issue_coverage", "noise_ratio", "comment_quality"]:
                avg_scores[key] = avg_scores.get(key, 0.0) + (val.score or 0.0)
                
    n = len(results)
    for key in avg_scores:
        avg_scores[key] /= n
        
    return avg_scores


