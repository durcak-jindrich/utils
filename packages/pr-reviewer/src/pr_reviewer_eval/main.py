def run_regression_test():
    """Performs regression testing by comparing current scores against baseline."""
    global DEGRADE_AGENT
    
    # Step 1: Run baseline (or check if baseline file exists)
    logger.info("--- PHASE 1: RUNNING BASELINE EVALUATION ---")
    DEGRADE_AGENT = False
    baseline_scores = run_evaluation_pipeline()
    
    # Save baseline scores
    try:
        with open(BASELINE_FILE, "w") as f:
            json.dump(baseline_scores, f, indent=2)
        logger.info(f"Baseline scores stored in: {BASELINE_FILE}")
    except Exception as e:
        logger.error(f"Failed to write baseline file: {e}")

    print("\n" + "="*40 + " BASELINE SCORES " + "="*40)
    for k, v in baseline_scores.items():
        print(f" - {k.replace('_', ' ').title()}: {v:.4f}")
    print("="*97 + "\n")

    # Step 2: Run Degraded evaluation (Comparison)
    logger.info("--- PHASE 2: RUNNING COMPARISON EVALUATION (DEGRADED AGENT) ---")
    DEGRADE_AGENT = True
    current_scores = run_evaluation_pipeline()
    
    print("\n" + "="*40 + " COMPARISON SCORES " + "="*40)
    for k, v in current_scores.items():
        print(f" - {k.replace('_', ' ').title()}: {v:.4f}")
    print("="*99 + "\n")

    # Step 3: Comparison logic and regression warning
    print("="*40 + " REGRESSION REPORT " + "="*40)
    regression_detected = False
    
    for metric in ["issue_coverage", "noise_ratio", "comment_quality"]:
        baseline = baseline_scores.get(metric, 0.0)
        current = current_scores.get(metric, 0.0)
        diff = baseline - current
        
        status = "PASSED"
        if diff > 0.1:
            status = "WARNING"
            regression_detected = True
            
        print(f" - {metric.replace('_', ' ').title():18} | Baseline: {baseline:.3f} | Current: {current:.3f} | Diff: {diff:+.3f} | Status: [{status}]")
        
        if status == "WARNING":
            print(f"   [!] WARNING: Evaluator '{metric}' dropped by {diff:.3f} (more than the threshold of 0.1)!")

    print("="*99 + "\n")
    
    if regression_detected:
        logger.warning("REGRESSION TEST DETECTED SIGNIFICANT PERFORMANCE DROP!")
    else:
        logger.info("REGRESSION TEST PASSED SUCCESSFULY.")


